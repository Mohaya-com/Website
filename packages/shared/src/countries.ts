export const PRIORITY_COUNTRIES: readonly string[] = ['SA', 'AE', 'KW', 'QA', 'BH', 'OM', 'EG', 'JO', 'YE', 'SY', 'LB', 'PS', 'IQ', 'SD', 'IN', 'PK', 'BD', 'PH', 'ID', 'NP', 'LK', 'US', 'GB'];

const byCode = new Map(COUNTRIES.map((c) => [c.code, c]));

export function countryName(code: string | null | undefined, locale: 'ar' | 'en'): string {
  if (!code) return '—';
  const c = byCode.get(code.toUpperCase());
  return c ? c[locale] : code;
}

export function getCountry(code: string | null | undefined): Country | undefined {
  return code ? byCode.get(code.toUpperCase()) : undefined;
}

/** Countries ordered for pickers: priority list first, then alphabetical in the requested language. */
export function sortedCountries(locale: 'ar' | 'en'): Country[] {
  const rest = COUNTRIES.filter((c) => !PRIORITY_COUNTRIES.includes(c.code)).sort((a, b) => a[locale].localeCompare(b[locale], locale));
  const first = PRIORITY_COUNTRIES.map((code) => byCode.get(code)).filter((c): c is Country => Boolean(c));
  return [...first, ...rest];
}
